#!/usr/bin/env python3
"""Regresión de check-migrations.py con migraciones de Alembic tal como las genera.

El riesgo es el falso positivo que empuja a desactivar el revisor: una migración
reversible marcada como «downgrade() vacío» porque Alembic escribe `-> None` en la
firma y un comentario `# ###` al principio del cuerpo. Le pasó a musicos con su
migración base (2026-10-26); hubo que editar la plantilla de Alembic para pasar.

    python3 .workflow/tests/test-check-migrations.py
"""

import importlib.util
import sys
from pathlib import Path

RUTA = Path(__file__).resolve().parent.parent / "check-migrations.py"
spec = importlib.util.spec_from_file_location("check_migrations", RUTA)
cm = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cm)

DROP = "op.drop" + "_table"

# Lo que escribe `alembic revision --autogenerate` sin tocar.
GENERADA = f"""revision = 'abc'
down_revision = None


def upgrade() -> None:
    # ### commands auto generated by Alembic - please adjust! ###
    op.create_table('t', sa.Column('id', sa.Integer()))
    # ### end Alembic commands ###


def downgrade() -> None:
    # ### commands auto generated by Alembic - please adjust! ###
    {DROP}('t')
    # ### end Alembic commands ###
"""

VACIA = """def upgrade() -> None:
    op.create_table('t', sa.Column('id', sa.Integer()))


def downgrade() -> None:
    # nada que deshacer
    pass
"""


def caso_generada_es_reversible():
    problema = cm.revisar_reversibilidad("migrations/versions/abc.py", GENERADA)
    assert problema is None, problema


def caso_drop_en_downgrade_no_cuenta_como_ida():
    ida = cm.parte_hacia_adelante("migrations/versions/abc.py", GENERADA)
    assert "create_table" in ida, ida
    assert DROP not in ida, ida


def caso_downgrade_vacio_se_sigue_marcando():
    problema = cm.revisar_reversibilidad("migrations/versions/abc.py", VACIA)
    assert problema and "vacío" in problema, problema


CASOS = [
    caso_generada_es_reversible,
    caso_drop_en_downgrade_no_cuenta_como_ida,
    caso_downgrade_vacio_se_sigue_marcando,
]


def main():
    fallos = 0
    for caso in CASOS:
        try:
            caso()
            print(f"  ✓ {caso.__name__}")
        except AssertionError as e:
            fallos += 1
            print(f"  ✗ {caso.__name__}: {e}")
    print()
    if fallos:
        print(f"❌ {fallos} de {len(CASOS)} casos fallaron.")
        return 1
    print(f"✓ {len(CASOS)} casos en verde.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
